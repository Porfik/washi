/* ftpd — FTP-сервер приёма книг (только пассивный режим), чтобы слать их из файловых менеджеров.
 *
 * Вход — любой логин; пароль — любой, если не задан xfer_set_password, иначе должен совпасть (после 3 неверных
 * соединение закрывается, каждая неверная — пауза ~1 с). Корень — папка библиотеки (после входа клиент — в папке приёма); папки system, applications и папка
 * хаба не видны и недоступны, выход за корень запрещён. Можно читать, класть новые файлы и
 * создавать папки; удалять, переименовывать и перезаписывать нельзя — зеркалирующий клиент
 * ничего не сотрёт. Файл пишется во временный и ставится на место после последнего байта.
 */
#ifndef WASHI_NET_FTPD_H
#define WASHI_NET_FTPD_H

#include "xfer.h"

#define FTPD_PORT 2121
#define FTPD_MAX_CLIENTS 4

typedef struct ftpd ftpd;

/* root — корень (library_root); hidden_dir — ещё одна скрытая папка (папка хаба; может быть
 * NULL или вне корня); home — папка, в которой клиент оказывается после входа (папка приёма;
 * должна быть уже создана и внутри корня, иначе — сам корень; «..» ведёт выше, до корня).
 * NULL — не вышло. */
ftpd *ftpd_start(xfer *log, const char *root, const char *hidden_dir, const char *home, int first_port);
int ftpd_port(const ftpd *f);
/* Куда попадает клиент после входа: виртуальный путь («/» или «/Downloads»). */
const char *ftpd_home(const ftpd *f);
void ftpd_stop(ftpd *f);

#endif
