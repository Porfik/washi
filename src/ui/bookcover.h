/* Обложка книги в рамке одного размера для всех книг (хаб, библиотека, карточка книги).
 *
 * Обложка заполняет рамку целиком: масштаб — по большей стороне, лишнее обрезается
 * (по ширине — поровну с краёв, по высоте — снизу: название обычно вверху). Углы
 * скруглены, тонкая рамка — чтобы белые поля обложки не сливались с фоном. Обложки нет
 * или она ещё рисуется — светлая подложка с названием (в маленькой рамке — со значком).
 * Рамки в хабе — 3 : 4 (BOOKCOVER_RATIO).
 */
#ifndef WASHI_UI_BOOKCOVER_H
#define WASHI_UI_BOOKCOVER_H

#include "../doc/covers.h"
#include "gfx.h"
#include "widgets.h"

/* Высота рамки обложки по ширине (3 : 4). */
#define BOOKCOVER_H(w) ((w) * 4 / 3)

/* bg — фон вокруг (им закрашиваются срезанные углы). 1 — обложка ещё рисуется. */
int ui_book_cover(gfx *g, pf_screen *s, covers *cv, ui_rect box, int radius, const char *path, uint8_t bg);

#endif
