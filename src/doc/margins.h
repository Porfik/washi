/* margins — поля книги: рамка содержимого для режима «без полей».
 *
 * Рамка одна на книгу (отдельно для нечётных и чётных страниц), чтобы при листании не
 * прыгал масштаб. Несколько страниц из середины книги рисуются мелко; на каждой ищется
 * рамка тёмных точек без полос сканера по краям; рамка книги — объединение, в котором
 * не учитывается одна самая выступающая страница с каждой стороны.
 */
#ifndef WASHI_DOC_MARGINS_H
#define WASHI_DOC_MARGINS_H

#include "doc.h"

/* Вызывается после каждой просмотренной страницы: done из total. */
typedef void (*margins_progress)(void *user, int done, int total);

/* Открывает path своей копией документа. out — рамки в долях страницы:
 * out[0..3] = x0, y0, x1, y1 нечётных страниц (номер с 0 чётный), out[4..7] — чётных.
 * 0 — найдено; -1 — не открылся документ или ни на одной странице нет содержимого. */
int margins_find(const char *path, const doc_options *opt, float out[8], margins_progress progress, void *user);

#endif
