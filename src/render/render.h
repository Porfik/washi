/* render — фоновые потоки отрисовки.
 *
 * У каждого потока своя копия документа (fz_document не потокобезопасен).
 * Поток интерфейса задаёт общий список нужных страниц по приоритету и забирает готовые;
 * сам поток интерфейса не будится — он проверяет готовность сам (по таймеру).
 */
#ifndef WASHI_RENDER_H
#define WASHI_RENDER_H

#include "../cache/cache.h"
#include "../doc/doc.h"

typedef struct renderer renderer;

/* Как вписывать страницу в экран. */
typedef enum {
    VIEW_FIT_PAGE,  /* страница целиком */
    VIEW_FIT_WIDTH, /* по ширине; страница выше экрана даёт картинку выше экрана (листается частями) */
    VIEW_CROP,      /* рамка содержимого (без полей) целиком */
} view_mode;

typedef struct {
    view_mode mode;
    /* VIEW_CROP: рамка содержимого в долях страницы (0..1): [0] — нечётные страницы
     * (1, 3, … — номер с 0 чётный), [1] — чётные. */
    doc_rect crop[2];
    int spread;   /* 1 — разворот: картинка страницы N — страницы N и N+1 рядом (как в книге) */
    int contrast; /* 0 — как есть; 1..3 — темнее текст и белее фон (для бледных сканов) */
} view_settings;


/* Забирает во владение count копий одного документа — по потоку на копию.
 * Страницы рисуются «по размеру» в width×height с шагом stride. */
renderer *renderer_new(doc **docs, int count, int width, int height, int stride);

/* Останавливает потоки (дожидается конца текущих операций MuPDF) и закрывает документы. */
void renderer_free(renderer *r);

/* Просит потоки закончить как можно скорее, не дожидаясь их (перед выходом процесса). */
void renderer_stop_async(renderer *r);

/* Новый список нужных страниц, самая нужная первой; заменяет прежний.
 * urgent — первая страница нужна на экран прямо сейчас.
 * Отрисовка прерывается, если её страницы нет в списке, или если первая срочная,
 * её никто не рисует и свободного потока нет (тогда — поток с наименее нужной страницей). */
void renderer_request(renderer *r, const int *pages, int count, int urgent);

/* on — пока срочная страница не готова, другие потоки не начинают новых страниц
 * (уже начатые не прерываются). Срочная получает все ядра: распаковка JPX в MuPDF
 * идёт под общей блокировкой и в двух потоках. */
void renderer_set_urgent_alone(renderer *r, int on);

/* Новый способ вписывать страницы. Начатые отрисовки прерываются, готовые и не забранные
 * выбрасываются; запрошенные дальше рисуются по-новому. */
void renderer_set_view(renderer *r, const view_settings *v);

/* Забирает готовые страницы (не больше max); возвращает их число. */
int renderer_collect(renderer *r, page_image **out, int max);

/* Есть работа: что-то рисуется, ждёт в списке или не забрано. */
int renderer_busy(renderer *r);

#endif
