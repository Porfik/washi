/* prof — профиль по сэмплам без внешних инструментов (на книге нет perf).
 *
 * SIGPROF каждые period_us микросекунд процессорного времени процесса; обработчик
 * запоминает адрес команды (и на ARM адрес возврата) прерванного потока. В файл
 * пишутся участки памяти с кодом из /proc/self/maps и счётчики адресов; имена
 * функций — потом на ПК по таблице символов той же сборки (scripts/prof-report.py).
 */
#ifndef WASHI_PROF_H
#define WASHI_PROF_H

/* 0 — запущен; -1 — нет памяти под сэмплы или setitimer не удался. */
int prof_start(int period_us);

/* Останавливает и пишет результат. Возвращает число сэмплов или -1. */
int prof_stop(const char *path);

#endif
