/* secret — пароли и логины в файлах настроек не открытым текстом.
 *
 * Значение хранится как «enc1:» + base64(вектор 16 байт | AES-256-CBC | HMAC-SHA256, 16 байт).
 * Ключ выводится (SHA-256) из pf_device_secret — ключа и серийного номера устройства из
 * прошивки: их нет в файлах, видных по USB, поэтому скопированные с книги opds.txt и sync.txt
 * ничего не выдают. От того, кто запустит свою программу на самой книге, это не защищает.
 * Если прошивка ничего не дала — ключ из случайного файла <папка данных>/secret.key (слабее:
 * файл лежит рядом; так на ПК).
 *
 * secret_init — один раз из потока интерфейса (зовёт платформу); потом seal и open можно
 * из любого потока.
 */
#ifndef WASHI_BASE_SECRET_H
#define WASHI_BASE_SECRET_H

#include <stddef.h>

void secret_init(void);

/* Зашифровать plain. 0 — out = «enc1:…»; -1 — не вышло (out пустая). out — не меньше
 * secret_sealed_len(strlen(plain)) + 1. Пустой plain → пустой out (нечего прятать). */
int secret_seal(const char *plain, char *out, size_t len);
size_t secret_sealed_len(size_t plain_len);

/* Расшифровать то, что прочитано из файла. Без «enc1:» — старое открытое значение,
 * отдаётся как есть (при следующей записи зашифруется). 0 — out готов; -1 — не
 * расшифровалось (другое устройство, файл испорчен): out пустая, пароль нужно ввести заново. */
int secret_open(const char *stored, char *out, size_t len);

/* Зашифровано ли значение (иначе — открытое, его стоит перезаписать). */
int secret_is_sealed(const char *stored);

#endif
